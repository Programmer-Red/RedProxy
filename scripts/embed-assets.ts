import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'server', 'src', 'generated', 'assets.ts');

function walk(dir: string, prefix: string, out: Array<{ key: string; file: string }>): void {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(absolute, `${prefix}/${entry.name}`, out);
    } else if (entry.isFile()) {
      out.push({ key: `${prefix}/${entry.name}`, file: absolute });
    }
  }
}

const files: Array<{ key: string; file: string }> = [];
walk(path.join(ROOT, 'public'), 'public', files);
walk(path.join(ROOT, 'extension-template'), 'extension-template', files);
files.sort((a, b) => a.key.localeCompare(b.key));

const assets: Record<string, string> = {};
for (const asset of files) {
  assets[asset.key] = fs.readFileSync(asset.file, 'utf8');
}

const header = `/* eslint-disable */
// This file is generated by scripts/embed-assets.ts. Do not edit by hand.
// It allows the compiled single-file server binary to serve the web UI and the
// extension template without needing sidecar files on disk.
export const EMBEDDED_ASSETS: Record<string, string> = ${JSON.stringify(assets, null, 2)};
`;
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, header, 'utf8');
console.log(`[embed-assets] wrote ${Object.keys(assets).length} assets to ${path.relative(ROOT, OUTPUT)}`);
